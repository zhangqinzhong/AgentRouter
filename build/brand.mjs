import {readFileSync,writeFileSync,copyFileSync,readdirSync} from 'node:fs';
import path from 'node:path';
export const root=path.resolve(import.meta.dirname,'..');
export const brand=JSON.parse(readFileSync(path.join(root,'build/brand.json'),'utf8'));
export function syncBrand() {
  const config=JSON.parse(readFileSync(path.join(root,'electron-builder.json'),'utf8'));
  if(config.productName!==brand.name || config.appId!==brand.appId || config.mac.icon!==brand.macIcon) throw Error('electron-builder.json differs from build/brand.json');
  if(config.mac.extendInfo?.CFBundleIconName!==brand.name || config.mac.extendInfo?.CFBundleIconFile!==brand.name)throw Error('Native icon metadata differs from brand configuration');
  const swift='// Generated by build/brand.mjs from build/brand.json.\n'+
    'enum AppBrand {\n'+Object.entries({name:brand.name,appId:brand.appId,website:brand.website,repository:brand.repository,iconFile:brand.nativeIconName}).map(([key,value])=>` static let ${key} = ${JSON.stringify(value)}\n`).join('')+'}\n';
  const target=path.join(root,'native/AgentRouterTray/Sources/AgentRouterTray/AppBrand.swift');
  let current;try{current=readFileSync(target,'utf8')}catch{}
  if(current!==swift)writeFileSync(target,swift);
  copyFileSync(path.join(root,brand.mark),path.join(root,'docs/public/agentrouter-mark.png'));
  const favicon = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><image width="1024" height="1024" href="data:image/png;base64,'+readFileSync(path.join(root,brand.favicon)).toString('base64')+'"/></svg>\n';
  writeFileSync(path.join(root,'docs/public/agentrouter-favicon.svg'),favicon);
  const ui=`// Generated from build/brand.json.\nimport appIconUrl from ${JSON.stringify('../../../../'+brand.uiIcon)};\nexport default appIconUrl;\n`;
  const uiTarget=path.join(root,'packages/ui/src/lib/app-icon.ts');
  if(readFileSync(uiTarget,'utf8')!==ui)writeFileSync(uiTarget,ui);
  for(const dir of ['native/AgentRouterTray/Sources','native/AgentRouterWidget/Sources','packages/ui/src','packages/electron/src'])checkDisplayBrand(path.join(root,dir));
}
function checkDisplayBrand(dir){
  for(const item of readdirSync(dir,{withFileTypes:true})){
    const file=path.join(dir,item.name);
    if(item.isDirectory()){checkDisplayBrand(file);continue;}
    if(!/\.(swift|tsx?|astro)$/.test(item.name))continue;
    const source=readFileSync(file,'utf8');
    if(/(?:Text\(\s*|[=:]\s*)["'](?:TokenTracker|Claude Code Router)["']/.test(source))throw Error(`Legacy display brand: ${path.relative(root,file)}`);
  }
}
if(process.argv[1] && path.resolve(process.argv[1])===path.join(root,'build/brand.mjs')){syncBrand();console.log('Brand resources and display-name checks passed.');}
